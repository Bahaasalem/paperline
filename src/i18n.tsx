const dicts: Record<Lang, Record<Key, string>> = { en, ar };

interface I18n {
  lang: Lang;
  dir: 'ltr' | 'rtl';
  t: (k: Key) => string;
  toggle: () => void;
}

const Ctx = createContext<I18n>(null as unknown as I18n);

function initialLang(): Lang {
  try {
    const v = localStorage.getItem('paperline.lang');
    if (v === 'ar' || v === 'en') return v;
  } catch {
    /* storage unavailable */
  }
  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);
  const dir = lang === 'ar' ? 'rtl' : 'ltr';
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    try {
      localStorage.setItem('paperline.lang', lang);
    } catch {
      /* ignore */
    }
  }, [lang, dir]);
  const value = useMemo<I18n>(
    () => ({ lang, dir, t: (k) => dicts[lang][k] ?? en[k], toggle: () => setLang((l) => (l === 'en' ? 'ar' : 'en')) }),
    [lang, dir],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
